-- 区号基础数据，用于固话号码识别、异地固话补 0 和后续按地区选线。
CREATE TABLE IF NOT EXISTS cc_area_code (
    id BIGINT NOT NULL COMMENT '区号ID',
    tenant_id VARCHAR(20) NOT NULL COMMENT '租户ID',
    country_code VARCHAR(8) NOT NULL DEFAULT '86' COMMENT '国家码',
    province VARCHAR(64) NOT NULL COMMENT '省份',
    city VARCHAR(64) NOT NULL COMMENT '城市',
    area_code VARCHAR(16) NOT NULL COMMENT '电话区号，包含前导0',
    enabled TINYINT NOT NULL DEFAULT 1 COMMENT '启用状态',
    create_dept BIGINT NULL COMMENT '创建部门',
    create_by BIGINT NULL COMMENT '创建人',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_by BIGINT NULL COMMENT '更新人',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除标志',
    PRIMARY KEY (id),
    UNIQUE KEY uk_cc_area_code (tenant_id, country_code, area_code, deleted),
    KEY idx_cc_area_code_city (tenant_id, province, city, enabled)
) ENGINE=InnoDB COMMENT='电话区号基础表';

